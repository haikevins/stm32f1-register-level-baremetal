#ifndef STM32F103XB_REGISTER_BITS_H
#define STM32F103XB_REGISTER_BITS_H

#include <stdint.h>

/* RCC_CR */
#define STM32_RCC_CR_HSION  (UINT32_C(1) << 0U)
#define STM32_RCC_CR_HSIRDY (UINT32_C(1) << 1U)
#define STM32_RCC_CR_HSEON  (UINT32_C(1) << 16U)
#define STM32_RCC_CR_HSERDY (UINT32_C(1) << 17U)
#define STM32_RCC_CR_PLLON  (UINT32_C(1) << 24U)
#define STM32_RCC_CR_PLLRDY (UINT32_C(1) << 25U)

/* RCC_CFGR */
#define STM32_RCC_CFGR_SW_MASK     (UINT32_C(0x3) << 0U)
#define STM32_RCC_CFGR_SW_HSI      (UINT32_C(0x0) << 0U)
#define STM32_RCC_CFGR_SW_PLL      (UINT32_C(0x2) << 0U)
#define STM32_RCC_CFGR_SWS_MASK    (UINT32_C(0x3) << 2U)
#define STM32_RCC_CFGR_SWS_HSI     (UINT32_C(0x0) << 2U)
#define STM32_RCC_CFGR_SWS_PLL     (UINT32_C(0x2) << 2U)
#define STM32_RCC_CFGR_HPRE_MASK   (UINT32_C(0xF) << 4U)
#define STM32_RCC_CFGR_PPRE1_MASK  (UINT32_C(0x7) << 8U)
#define STM32_RCC_CFGR_PPRE1_DIV1  (UINT32_C(0x0) << 8U)
#define STM32_RCC_CFGR_PPRE1_DIV2  (UINT32_C(0x4) << 8U)
#define STM32_RCC_CFGR_PPRE2_MASK  (UINT32_C(0x7) << 11U)
#define STM32_RCC_CFGR_ADCPRE_MASK (UINT32_C(0x3) << 14U)
#define STM32_RCC_CFGR_ADCPRE_DIV2 (UINT32_C(0x0) << 14U)
#define STM32_RCC_CFGR_ADCPRE_DIV4 (UINT32_C(0x1) << 14U)
#define STM32_RCC_CFGR_ADCPRE_DIV6 (UINT32_C(0x2) << 14U)
#define STM32_RCC_CFGR_ADCPRE_DIV8 (UINT32_C(0x3) << 14U)
#define STM32_RCC_CFGR_PLLSRC_HSE  (UINT32_C(1) << 16U)
#define STM32_RCC_CFGR_PLLXTPRE    (UINT32_C(1) << 17U)
#define STM32_RCC_CFGR_PLLMUL_MASK (UINT32_C(0xF) << 18U)
#define STM32_RCC_CFGR_PLLMUL_ENCODE(multiplier) \
    (((uint32_t)((multiplier) - 2U) & UINT32_C(0xF)) << 18U)

/* RCC_APB2ENR */
#define STM32_RCC_APB2ENR_IOPAEN   (UINT32_C(1) << 2U)
#define STM32_RCC_APB2ENR_IOPBEN   (UINT32_C(1) << 3U)
#define STM32_RCC_APB2ENR_IOPCEN   (UINT32_C(1) << 4U)
#define STM32_RCC_APB2ENR_IOPDEN   (UINT32_C(1) << 5U)
#define STM32_RCC_APB2ENR_IOPEEN   (UINT32_C(1) << 6U)
#define STM32_RCC_APB2ENR_ADC1EN   (UINT32_C(1) << 9U)
#define STM32_RCC_APB2ENR_USART1EN (UINT32_C(1) << 14U)

/* RCC_APB2RSTR */
#define STM32_RCC_APB2RSTR_ADC1RST (UINT32_C(1) << 9U)

/* RCC_AHBENR */
#define STM32_RCC_AHBENR_DMA1EN (UINT32_C(1) << 0U)

/* RCC_APB1ENR */
#define STM32_RCC_APB1ENR_TIM2EN (UINT32_C(1) << 0U)
#define STM32_RCC_APB1ENR_TIM3EN (UINT32_C(1) << 1U)
#define STM32_RCC_APB1ENR_I2C1EN (UINT32_C(1) << 21U)

/* RCC_APB1RSTR */
#define STM32_RCC_APB1RSTR_I2C1RST (UINT32_C(1) << 21U)

/* TIMx_CR1 */
#define STM32_TIM_CR1_CEN  (UINT32_C(1) << 0U)
#define STM32_TIM_CR1_ARPE (UINT32_C(1) << 7U)

/* TIMx_CR2 */
#define STM32_TIM_CR2_MMS_MASK   (UINT32_C(0x7) << 4U)
#define STM32_TIM_CR2_MMS_UPDATE (UINT32_C(0x2) << 4U)

/* TIMx_EGR */
#define STM32_TIM_EGR_UG (UINT32_C(1) << 0U)

/* TIMx_CCMR1, output compare channel 1 */
#define STM32_TIM_CCMR1_OC1PE       (UINT32_C(1) << 3U)
#define STM32_TIM_CCMR1_OC1M_MASK   (UINT32_C(0x7) << 4U)
#define STM32_TIM_CCMR1_OC1M_PWM1   (UINT32_C(0x6) << 4U)

/* TIMx_CCER */
#define STM32_TIM_CCER_CC1E (UINT32_C(1) << 0U)


/* I2Cx_CR1 */
#define STM32_I2C_CR1_PE    (UINT32_C(1) << 0U)
#define STM32_I2C_CR1_START (UINT32_C(1) << 8U)
#define STM32_I2C_CR1_STOP  (UINT32_C(1) << 9U)

/* I2Cx_CR2 */
#define STM32_I2C_CR2_FREQ_MASK (UINT32_C(0x3F))

/* I2Cx_OAR1 */
#define STM32_I2C_OAR1_BIT14 (UINT32_C(1) << 14U)

/* I2Cx_SR1 */
#define STM32_I2C_SR1_SB      (UINT32_C(1) << 0U)
#define STM32_I2C_SR1_ADDR    (UINT32_C(1) << 1U)
#define STM32_I2C_SR1_BTF     (UINT32_C(1) << 2U)
#define STM32_I2C_SR1_TXE     (UINT32_C(1) << 7U)
#define STM32_I2C_SR1_BERR    (UINT32_C(1) << 8U)
#define STM32_I2C_SR1_ARLO    (UINT32_C(1) << 9U)
#define STM32_I2C_SR1_AF      (UINT32_C(1) << 10U)
#define STM32_I2C_SR1_OVR     (UINT32_C(1) << 11U)
#define STM32_I2C_SR1_TIMEOUT (UINT32_C(1) << 14U)
#define STM32_I2C_SR1_ERROR_MASK \
    (STM32_I2C_SR1_BERR | STM32_I2C_SR1_ARLO | \
     STM32_I2C_SR1_AF | STM32_I2C_SR1_OVR | \
     STM32_I2C_SR1_TIMEOUT)

/* I2Cx_SR2 */
#define STM32_I2C_SR2_BUSY (UINT32_C(1) << 1U)

/* I2Cx_CCR */
#define STM32_I2C_CCR_CCR_MASK (UINT32_C(0x0FFF))
#define STM32_I2C_CCR_FS       (UINT32_C(1) << 15U)

/* I2Cx_TRISE */
#define STM32_I2C_TRISE_MASK (UINT32_C(0x3F))


/* ADCx_CR2 */
#define STM32_ADC_CR2_ADON              (UINT32_C(1) << 0U)
#define STM32_ADC_CR2_CAL               (UINT32_C(1) << 2U)
#define STM32_ADC_CR2_RSTCAL            (UINT32_C(1) << 3U)
#define STM32_ADC_CR2_DMA               (UINT32_C(1) << 8U)
#define STM32_ADC_CR2_EXTSEL_MASK       (UINT32_C(0x7) << 17U)
#define STM32_ADC_CR2_EXTSEL_TIM3_TRGO  (UINT32_C(0x4) << 17U)
#define STM32_ADC_CR2_EXTTRIG           (UINT32_C(1) << 20U)

/* ADC sample-time encoding */
#define STM32_ADC_SAMPLE_55_CYCLES_5 (UINT32_C(0x5))

/* DMA1 ISR, Channel 1 */
#define STM32_DMA_ISR_GIF1  (UINT32_C(1) << 0U)
#define STM32_DMA_ISR_TCIF1 (UINT32_C(1) << 1U)
#define STM32_DMA_ISR_HTIF1 (UINT32_C(1) << 2U)
#define STM32_DMA_ISR_TEIF1 (UINT32_C(1) << 3U)

/* DMA1 IFCR, Channel 1 */
#define STM32_DMA_IFCR_CGIF1  (UINT32_C(1) << 0U)
#define STM32_DMA_IFCR_CTCIF1 (UINT32_C(1) << 1U)
#define STM32_DMA_IFCR_CHTIF1 (UINT32_C(1) << 2U)
#define STM32_DMA_IFCR_CTEIF1 (UINT32_C(1) << 3U)

/* DMA channel CCR */
#define STM32_DMA_CCR_EN           (UINT32_C(1) << 0U)
#define STM32_DMA_CCR_TCIE         (UINT32_C(1) << 1U)
#define STM32_DMA_CCR_HTIE         (UINT32_C(1) << 2U)
#define STM32_DMA_CCR_TEIE         (UINT32_C(1) << 3U)
#define STM32_DMA_CCR_CIRC         (UINT32_C(1) << 5U)
#define STM32_DMA_CCR_MINC         (UINT32_C(1) << 7U)
#define STM32_DMA_CCR_PSIZE_16BIT  (UINT32_C(0x1) << 8U)
#define STM32_DMA_CCR_MSIZE_16BIT  (UINT32_C(0x1) << 10U)
#define STM32_DMA_CCR_PL_HIGH      (UINT32_C(0x2) << 12U)

/* USART_SR */
#define STM32_USART_SR_PE         (UINT32_C(1) << 0U)
#define STM32_USART_SR_FE         (UINT32_C(1) << 1U)
#define STM32_USART_SR_NE         (UINT32_C(1) << 2U)
#define STM32_USART_SR_ORE        (UINT32_C(1) << 3U)
#define STM32_USART_SR_RXNE       (UINT32_C(1) << 5U)
#define STM32_USART_SR_TC         (UINT32_C(1) << 6U)
#define STM32_USART_SR_TXE        (UINT32_C(1) << 7U)
#define STM32_USART_SR_ERROR_MASK \
    (STM32_USART_SR_PE | STM32_USART_SR_FE | \
     STM32_USART_SR_NE | STM32_USART_SR_ORE)

/* USART_CR1 */
#define STM32_USART_CR1_RE     (UINT32_C(1) << 2U)
#define STM32_USART_CR1_TE     (UINT32_C(1) << 3U)
#define STM32_USART_CR1_RXNEIE (UINT32_C(1) << 5U)
#define STM32_USART_CR1_TXEIE  (UINT32_C(1) << 7U)
#define STM32_USART_CR1_UE     (UINT32_C(1) << 13U)

/* FLASH_ACR */
#define STM32_FLASH_ACR_LATENCY_MASK (UINT32_C(0x7) << 0U)
#define STM32_FLASH_ACR_LATENCY_0    (UINT32_C(0x0) << 0U)
#define STM32_FLASH_ACR_LATENCY_1    (UINT32_C(0x1) << 0U)
#define STM32_FLASH_ACR_LATENCY_2    (UINT32_C(0x2) << 0U)
#define STM32_FLASH_ACR_PRFTBE       (UINT32_C(1) << 4U)

#endif
