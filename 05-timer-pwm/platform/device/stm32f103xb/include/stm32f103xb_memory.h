#ifndef STM32F103XB_MEMORY_H
#define STM32F103XB_MEMORY_H

#include <stdint.h>

#define STM32_FLASH_MEMORY_BASE (UINT32_C(0x08000000))
#define STM32_SRAM_BASE         (UINT32_C(0x20000000))

#define STM32_PERIPH_BASE       (UINT32_C(0x40000000))
#define STM32_APB1_BASE         STM32_PERIPH_BASE
#define STM32_APB2_BASE         (UINT32_C(0x40010000))
#define STM32_AHB_BASE          (UINT32_C(0x40018000))

#define STM32_TIM2_BASE         (STM32_APB1_BASE + UINT32_C(0x0000))

#define STM32_GPIOA_BASE        (STM32_APB2_BASE + UINT32_C(0x0800))
#define STM32_GPIOB_BASE        (STM32_APB2_BASE + UINT32_C(0x0C00))
#define STM32_GPIOC_BASE        (STM32_APB2_BASE + UINT32_C(0x1000))
#define STM32_GPIOD_BASE        (STM32_APB2_BASE + UINT32_C(0x1400))
#define STM32_GPIOE_BASE        (STM32_APB2_BASE + UINT32_C(0x1800))
#define STM32_USART1_BASE       (STM32_APB2_BASE + UINT32_C(0x3800))

#define STM32_RCC_BASE          (STM32_AHB_BASE + UINT32_C(0x9000))
#define STM32_FLASH_REG_BASE    (STM32_AHB_BASE + UINT32_C(0xA000))

#endif
